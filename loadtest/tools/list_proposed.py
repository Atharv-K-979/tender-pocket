#!/usr/bin/env python3
"""List every config value marked "# PROPOSED – not approved" (G5).

    python3 tools/list_proposed.py            # table to stdout
    python3 tools/list_proposed.py --md docs  # also write docs/loadtest/proposed-values.md

A marker on a section header applies to the whole block below it.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "PROPOSED"


def scan() -> list[tuple[str, int, str]]:
    out = []
    files = sorted((ROOT / "config").glob("*.yaml")) + sorted((ROOT / "k6" / "profiles").glob("*.yaml"))
    for f in files:
        if f.name == "env.yaml":
            continue
        for i, line in enumerate(f.read_text(encoding="utf-8").splitlines(), start=1):
            if MARK in line:
                text = line.split("#", 1)[0].strip() or line.strip().lstrip("#").strip()
                out.append((str(f.relative_to(ROOT)), i, text[:140]))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", action="store_true")
    a = ap.parse_args(argv)
    rows = scan()
    for f, i, t in rows:
        print(f"{f}:{i}\t{t}")
    print(f"\n{len(rows)} PROPOSED markers")
    if a.md:
        md = ["# PROPOSED values awaiting approval", "",
              "Generated by `loadtest/tools/list_proposed.py`. Each value below is a default that has not been approved. "
              "A marker on a section header covers the whole block. Approve a value or change it, then remove its marker.", "",
              "| file:line | value |", "|---|---|"]
        md += [f"| `{f}:{i}` | `{t.replace('|', '/')}` |" for f, i, t in rows]
        p = ROOT.parent / "docs" / "loadtest" / "proposed-values.md"
        p.write_text("\n".join(md) + "\n")
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
